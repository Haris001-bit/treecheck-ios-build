// Copies the large-company pricing engine (src/lib/production) to supabase/functions/_shared/production so the edge
// functions price exactly as the screens do. Run after any change: node scripts/sync-production-engine.mjs
// src/lib/production/sharedCopy.test.ts fails when the copy is out of date.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

export const PRODUCTION_SHARED_FILES = [
  'engine.ts', 'rules.ts', 'answers.ts', 'productionRules.ts', 'profiles.ts', 'pricing.ts', 'costs.ts', 'contradictions.ts',
  'playbooks.ts', 'packaging.ts', 'capacity.ts', 'reports.ts', 'proposal.ts', 'validation.ts', 'aiFacts.ts', 'importSheet.ts',
  'starter.ts', 'estimate.ts', 'quoteLines.ts',
];

export const HEADER = '// Generated by scripts/sync-production-engine.mjs from src/lib/production. Do not edit here: edit the source and re-run.\n';

/** Deno needs file extensions and npm: specifiers; everything else stays byte for byte. */
export function toDeno(src) {
  return HEADER + src
    .replace(/from '(\.\/[A-Za-z0-9_]+)'/g, "from '$1.ts'")
    .replace(/from 'zod'/g, "from 'npm:zod@3'");
}

if (process.argv[1] && process.argv[1].endsWith('sync-production-engine.mjs')) {
  mkdirSync('supabase/functions/_shared/production', { recursive: true });
  for (const f of PRODUCTION_SHARED_FILES) {
    const src = readFileSync(`src/lib/production/${f}`, 'utf8').replace(/\r\n/g, '\n');
    writeFileSync(`supabase/functions/_shared/production/${f}`, toDeno(src));
  }
  console.log(`Copied ${PRODUCTION_SHARED_FILES.length} files to supabase/functions/_shared/production`);
}
