// Import graph of TreeCheck's Supabase edge functions (Jobber sync plan, section 4).
//
// A shared file reaches users only when every function that imports it is redeployed. This script
// walks each supabase/functions/<name>/index.ts through its relative imports, transitively, and
// lists the shared files each function pulls in: every file outside the function's own folder,
// which today is always _shared/. Imports are read from the source text: static imports,
// re-exports, side-effect imports and dynamic imports of a fixed path. npm:, jsr: and URL imports
// are not files in this repo and are skipped.
//
// Run from anywhere (Node 18 or later, no packages):
//   node scripts/jobber-import-graph.mjs
//       Writes docs/jobber-sync/import-graph.json.
//   node scripts/jobber-import-graph.mjs --check
//       Exits 1 when the saved manifest no longer matches the code.
//   node scripts/jobber-import-graph.mjs deploy-list <changed path> [<changed path> ...]
//   git diff --name-only origin/capacitor...HEAD | node scripts/jobber-import-graph.mjs deploy-list
//       Prints, one per line, every function whose own folder or import graph holds a changed
//       path. Paths may be repo-relative, absolute, or relative to supabase/functions. With no
//       paths on the command line they are read from standard input.
//
// deploy-list reads the current code every time, so it is never stale. The saved manifest exists
// so that a pull request shows every change to what a function imports; the guard test
// src/lib/jobberSync/guards.test.ts fails while the manifest is out of date.

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Repo-relative path of the saved manifest. */
export const MANIFEST_PATH = "docs/jobber-sync/import-graph.json";

const FUNCTIONS_DIR = "supabase/functions";
// A relative path to a code file. A "$" means a template string (generated code), never an import.
const LOCAL_FILE = /^\.\.?\/[^$]*\.(ts|tsx|mts|js|jsx|mjs|json)$/;
const ABOUT =
  "Generated by scripts/jobber-import-graph.mjs, do not edit by hand. Each edge function " +
  "(supabase/functions/<name>/index.ts) and the shared files it imports, directly or through other " +
  "files. Paths are relative to supabase/functions.";

const posix = (p) => p.replace(/\\/g, "/");

/** The edge function names: folders under supabase/functions that hold an index.ts, sorted. */
export function functionNames(repoRoot) {
  const dir = join(repoRoot, FUNCTIONS_DIR);
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !/^[_.]/.test(e.name) && existsSync(join(dir, e.name, "index.ts")))
    .map((e) => e.name)
    .sort();
}

/** The relative file imports written in one source file, in order; comment lines are skipped. */
export function localImports(source) {
  const found = [];
  for (const line of source.split(/\r?\n/)) {
    if (/^\s*(\/\/|\/\*|\*)/.test(line)) continue;
    const patterns = [/\bfrom\s*(["'])(.+?)\1/g, /^\s*import\s*(["'])(.+?)\1/g, /\bimport\s*\(\s*(["'])(.+?)\1\s*\)/g];
    for (const pattern of patterns) {
      for (const m of line.matchAll(pattern)) if (LOCAL_FILE.test(m[2])) found.push(m[2]);
    }
  }
  return found;
}

/** Every file reachable from one function's index.ts (itself included), relative to supabase/functions, sorted. */
export function functionFiles(repoRoot, name) {
  const base = join(repoRoot, FUNCTIONS_DIR);
  const seen = new Set();
  const queue = [join(base, name, "index.ts")];
  while (queue.length) {
    const file = queue.pop();
    const rel = posix(relative(base, file));
    if (seen.has(rel)) continue;
    seen.add(rel);
    // A missing file is a broken import: it stays in the list and the command line reports it.
    if (!existsSync(file)) continue;
    for (const spec of localImports(readFileSync(file, "utf8"))) queue.push(resolve(dirname(file), spec));
  }
  return [...seen].sort();
}

/** The manifest: each function mapped to the sorted shared files it imports, directly or indirectly. */
export function buildManifest(repoRoot) {
  const functions = {};
  for (const name of functionNames(repoRoot)) {
    functions[name] = functionFiles(repoRoot, name).filter((f) => !f.startsWith(`${name}/`));
  }
  return { about: ABOUT, functions };
}

/** The manifest exactly as it is written to disk. */
export function manifestText(manifest) {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

// A changed path as given (repo-relative, absolute, or relative to supabase/functions), made absolute.
function absoluteOf(repoRoot, path) {
  if (isAbsolute(path)) return path;
  if (path.startsWith("supabase/") || existsSync(join(repoRoot, path))) return join(repoRoot, path);
  return join(repoRoot, FUNCTIONS_DIR, path);
}

// Which functions the changed paths reach, and which paths reach none.
function changeImpact(repoRoot, changedPaths) {
  const base = join(repoRoot, FUNCTIONS_DIR);
  const changed = [...new Set(changedPaths.map((p) => posix(p.trim())).filter(Boolean))].map((p) => ({
    given: p,
    rel: posix(relative(base, absoluteOf(repoRoot, p))),
  }));
  const reached = new Set();
  const functions = functionNames(repoRoot).filter((name) => {
    const files = new Set(functionFiles(repoRoot, name));
    const hits = changed.filter((c) => c.rel.startsWith(`${name}/`) || files.has(c.rel));
    for (const c of hits) reached.add(c.given);
    return hits.length > 0;
  });
  return { functions, unmatched: changed.map((c) => c.given).filter((p) => !reached.has(p)) };
}

/** The functions to redeploy when the given paths change, sorted. */
export function deployList(repoRoot, changedPaths) {
  return changeImpact(repoRoot, changedPaths).functions;
}

function usage() {
  console.error(
    "usage: node scripts/jobber-import-graph.mjs            write the manifest\n" +
      "       node scripts/jobber-import-graph.mjs --check    exit 1 if the manifest is out of date\n" +
      "       node scripts/jobber-import-graph.mjs deploy-list <changed path> ...   (or paths on stdin)",
  );
  return 2;
}

function main(args) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const [mode, ...rest] = args;

  if (mode === "deploy-list") {
    let paths = rest;
    if (!paths.length) {
      if (process.stdin.isTTY) return usage();
      paths = readFileSync(0, "utf8").split(/\r?\n/);
    }
    const { functions, unmatched } = changeImpact(root, paths);
    for (const p of unmatched) console.error(`not in any edge function: ${p}`);
    for (const name of functions) console.log(name);
    return 0;
  }

  const manifest = buildManifest(root);
  const fresh = manifestText(manifest);
  const target = join(root, MANIFEST_PATH);
  for (const [name, files] of Object.entries(manifest.functions)) {
    for (const f of files) {
      if (!existsSync(join(root, FUNCTIONS_DIR, f))) console.error(`warning: ${name} imports a missing file: ${f}`);
    }
  }

  if (mode === "--check") {
    const saved = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
    if (saved === fresh) {
      console.log(`${MANIFEST_PATH} is current.`);
      return 0;
    }
    console.error(`${MANIFEST_PATH} is out of date. Run: node scripts/jobber-import-graph.mjs`);
    return 1;
  }
  if (mode !== undefined) return usage();

  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, fresh);
  console.log(`Wrote ${MANIFEST_PATH} (${Object.keys(manifest.functions).length} functions).`);
  return 0;
}

const invokedAs = process.argv[1] ? resolve(process.argv[1]).toLowerCase() : "";
if (invokedAs === fileURLToPath(import.meta.url).toLowerCase()) process.exitCode = main(process.argv.slice(2));
